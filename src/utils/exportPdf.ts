import jsPDF from 'jspdf';
import autoTable from 'jspdf-autotable';
import { CompletedPurchase, CompletedPurchaseItem } from '../types/wholesale';
import { formatPHP } from './formatCurrency';

/**
 * Cleanly format raw numbers as currency for PDF
 */
const formatMoney = (val: number): string => {
  return `PHP ${Number(val || 0).toLocaleString('en-PH', {
    minimumFractionDigits: 2,
    maximumFractionDigits: 2,
  })}`;
};

/**
 * Export a single purchase transaction / receipt as a downloadable PDF file
 */
export const exportSinglePurchasePdf = (purchase: CompletedPurchase) => {
  const doc = new jsPDF({
    orientation: 'portrait',
    unit: 'mm',
    format: 'a4',
  });

  const pageWidth = doc.internal.pageSize.getWidth();

  // Header Banner
  doc.setFillColor(15, 23, 42); // slate-900
  doc.rect(0, 0, pageWidth, 28, 'F');

  // Accent Line
  doc.setFillColor(245, 158, 11); // amber-500
  doc.rect(0, 28, pageWidth, 2.5, 'F');

  // Header Text
  doc.setTextColor(255, 255, 255);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(16);
  doc.text('MOTOPARTS WHOLESALE', 14, 12);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9);
  doc.setTextColor(203, 213, 225); // slate-300
  doc.text('OFFICIAL WHOLESALE PURCHASE VOUCHER & RECEIPT', 14, 18);

  // Order Details Box
  doc.setTextColor(15, 23, 42);
  doc.setFontSize(10);
  doc.setFont('helvetica', 'bold');
  doc.text(`Order Ref: ${purchase.id}`, 14, 38);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9);
  doc.setTextColor(71, 85, 105); // slate-600
  doc.text(`Date: ${purchase.dateFormatted}   Time: ${purchase.timeFormatted}`, 14, 44);
  doc.text(`Customer / Buyer: ${purchase.buyerName || 'Walk-in Buyer'}`, 14, 50);

  doc.text(`Total Items: ${purchase.totalUnits} pcs   |   Lines: ${purchase.items.length}`, pageWidth - 14, 44, { align: 'right' });
  doc.setFont('helvetica', 'bold');
  doc.setTextColor(217, 119, 6); // amber-600
  doc.text(`Grand Total: ${formatMoney(purchase.grandTotal)}`, pageWidth - 14, 50, { align: 'right' });

  // Items Table
  const tableRows = purchase.items.map((item, idx) => [
    (idx + 1).toString(),
    item.partNumber,
    item.itemName,
    item.brand.toUpperCase(),
    formatMoney(item.unitPrice),
    item.quantity.toString(),
    formatMoney(item.subtotal),
  ]);

  autoTable(doc, {
    startY: 56,
    head: [['#', 'Part #', 'Item Name', 'Brand', 'Price (PHP)', 'Qty', 'Subtotal (PHP)']],
    body: tableRows,
    theme: 'grid',
    headStyles: {
      fillColor: [30, 41, 59], // slate-800
      textColor: [255, 255, 255],
      fontStyle: 'bold',
      fontSize: 8.5,
      halign: 'left',
    },
    styles: {
      fontSize: 8,
      cellPadding: 2.5,
      textColor: [15, 23, 42],
    },
    columnStyles: {
      0: { cellWidth: 8, halign: 'center' },
      1: { cellWidth: 26, fontStyle: 'bold' },
      2: { cellWidth: 'auto' },
      3: { cellWidth: 24 },
      4: { cellWidth: 26, halign: 'right' },
      5: { cellWidth: 14, halign: 'center', fontStyle: 'bold' },
      6: { cellWidth: 28, halign: 'right', fontStyle: 'bold' },
    },
    alternateRowStyles: {
      fillColor: [248, 250, 252], // slate-50
    },
    margin: { left: 14, right: 14 },
  });

  // Footer summary on table end
  const finalY = ((doc as any).lastAutoTable?.finalY || 120) + 8;

  // Grand Total Box
  doc.setFillColor(241, 245, 249);
  doc.setDrawColor(203, 213, 225);
  doc.roundedRect(pageWidth - 85, finalY, 71, 24, 2, 2, 'FD');

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(8.5);
  doc.setTextColor(71, 85, 105);
  doc.text(`Total Quantity: ${purchase.totalUnits} pcs`, pageWidth - 80, finalY + 7);

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(11);
  doc.setTextColor(15, 23, 42);
  doc.text('TOTAL AMOUNT:', pageWidth - 80, finalY + 16);

  doc.setTextColor(180, 83, 9); // amber-700
  doc.text(formatMoney(purchase.grandTotal), pageWidth - 18, finalY + 16, { align: 'right' });

  if (purchase.shopPriceMargin && purchase.shopPriceMargin > 0) {
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(8.5);
    doc.setTextColor(16, 185, 129); // emerald-600
    doc.text(`Shop Price Margin: +${formatMoney(purchase.shopPriceMargin)}`, 14, finalY + 12);
  }

  // Thank You / Note
  doc.setFont('helvetica', 'italic');
  doc.setFontSize(8);
  doc.setTextColor(148, 163, 184); // slate-400
  doc.text(
    'Thank you for your purchase! Generated by MotoParts Pricelist & Wholesale Estimator.',
    14,
    finalY + 32
  );

  // Trigger browser download
  const safeRef = purchase.id.replace(/[^a-zA-Z0-9-_]/g, '_');
  doc.save(`Wholesale_Receipt_${safeRef}.pdf`);
};

/**
 * Export ALL completed wholesale purchase history into a consolidated multi-item PDF report
 */
export const exportAllPurchaseHistoryPdf = (history: CompletedPurchase[]) => {
  if (!history || history.length === 0) return;

  const doc = new jsPDF({
    orientation: 'portrait',
    unit: 'mm',
    format: 'a4',
  });

  const pageWidth = doc.internal.pageSize.getWidth();

  // Header Banner
  doc.setFillColor(15, 23, 42); // slate-900
  doc.rect(0, 0, pageWidth, 28, 'F');

  // Amber Accent Line
  doc.setFillColor(245, 158, 11); // amber-500
  doc.rect(0, 28, pageWidth, 2.5, 'F');

  // Title
  doc.setTextColor(255, 255, 255);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(16);
  doc.text('MOTOPARTS WHOLESALE', 14, 12);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9);
  doc.setTextColor(203, 213, 225);
  doc.text('COMPLETED WHOLESALE PURCHASES & SALES HISTORY REPORT', 14, 18);

  const totalOrders = history.length;
  const totalUnits = history.reduce((sum, p) => sum + p.totalUnits, 0);
  const totalRevenue = history.reduce((sum, p) => sum + p.grandTotal, 0);

  // Summary Metrics Bar
  doc.setTextColor(15, 23, 42);
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(8.5);
  doc.setTextColor(71, 85, 105);
  const genDate = new Date().toLocaleDateString('en-PH', { dateStyle: 'medium' });
  const genTime = new Date().toLocaleTimeString('en-PH', { timeStyle: 'short' });
  doc.text(`Report Generated: ${genDate} at ${genTime}`, 14, 37);

  // Metric Boxes
  doc.setFillColor(241, 245, 249);
  doc.setDrawColor(226, 232, 240);
  doc.roundedRect(14, 41, 55, 16, 2, 2, 'FD');
  doc.roundedRect(73, 41, 55, 16, 2, 2, 'FD');
  doc.roundedRect(132, 41, 64, 16, 2, 2, 'FD');

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(7.5);
  doc.setTextColor(100, 116, 139);
  doc.text('TOTAL ORDERS', 18, 46);
  doc.text('TOTAL UNITS SOLD', 77, 46);
  doc.text('TOTAL WHOLESALE REVENUE', 136, 46);

  doc.setFontSize(11);
  doc.setTextColor(15, 23, 42);
  doc.text(totalOrders.toString(), 18, 53);

  doc.setTextColor(217, 119, 6); // amber-600
  doc.text(`${totalUnits.toLocaleString()} pcs`, 77, 53);

  doc.setTextColor(16, 185, 129); // emerald-600
  doc.text(formatMoney(totalRevenue), 136, 53);

  // Table Data
  const tableRows = history.map((purchase) => {
    // Generate concise summary of items
    const itemsSummary = purchase.items
      .map((i) => `${i.itemName} (${i.quantity}x)`)
      .join(', ');

    return [
      `${purchase.dateFormatted}\n${purchase.timeFormatted}`,
      purchase.id,
      purchase.buyerName || 'Walk-in Buyer',
      itemsSummary,
      `${purchase.totalUnits} pcs`,
      formatMoney(purchase.grandTotal),
    ];
  });

  autoTable(doc, {
    startY: 62,
    head: [['Date & Time', 'Order ID', 'Buyer / Customer', 'Purchased Items', 'Qty', 'Total (PHP)']],
    body: tableRows,
    theme: 'grid',
    headStyles: {
      fillColor: [30, 41, 59], // slate-800
      textColor: [255, 255, 255],
      fontStyle: 'bold',
      fontSize: 8,
      halign: 'left',
    },
    styles: {
      fontSize: 7.5,
      cellPadding: 2.5,
      textColor: [15, 23, 42],
    },
    columnStyles: {
      0: { cellWidth: 26, fontStyle: 'normal' },
      1: { cellWidth: 26, fontStyle: 'bold' },
      2: { cellWidth: 28 },
      3: { cellWidth: 'auto' },
      4: { cellWidth: 16, halign: 'center', fontStyle: 'bold' },
      5: { cellWidth: 28, halign: 'right', fontStyle: 'bold', textColor: [180, 83, 9] },
    },
    alternateRowStyles: {
      fillColor: [248, 250, 252],
    },
    margin: { left: 14, right: 14 },
    foot: [
      [
        'Total Summary',
        `${totalOrders} orders`,
        '-',
        'All purchases to date',
        `${totalUnits} pcs`,
        formatMoney(totalRevenue),
      ],
    ],
    footStyles: {
      fillColor: [15, 23, 42],
      textColor: [255, 255, 255],
      fontStyle: 'bold',
      fontSize: 8.5,
      halign: 'right',
    },
  });

  const finalY = ((doc as any).lastAutoTable?.finalY || 160) + 10;
  if (finalY < 280) {
    doc.setFont('helvetica', 'italic');
    doc.setFontSize(8);
    doc.setTextColor(148, 163, 184);
    doc.text(
      'End of Purchase History Report. Generated by MotoParts Wholesale Management System.',
      14,
      finalY
    );
  }

  const dateSlug = new Date().toISOString().slice(0, 10);
  doc.save(`MotoParts_Wholesale_Purchase_History_${dateSlug}.pdf`);
};

/**
 * Export current active estimate as a PDF quotation/estimate
 */
export const exportEstimateQuotationPdf = (data: {
  buyerName: string;
  items: CompletedPurchaseItem[];
  totalUnits: number;
  grandTotal: number;
  dateFormatted: string;
  timeFormatted: string;
}) => {
  const tempPurchase: CompletedPurchase = {
    id: `EST-${Date.now().toString().slice(-6)}`,
    timestamp: new Date().toISOString(),
    dateFormatted: data.dateFormatted,
    timeFormatted: data.timeFormatted,
    buyerName: data.buyerName.trim() || 'Valued Customer',
    items: data.items,
    totalUnits: data.totalUnits,
    grandTotal: data.grandTotal,
  };

  exportSinglePurchasePdf(tempPurchase);
};
